"""SFT trainer: LoRA fine-tune google/gemma-4-E4B-it on the menu-extraction corpus.

Consumes `data/sft/<family>/train.jsonl` (produced by scripts/datasets/build_sft.py):
one JSON object per line with a Gemma-format `messages` list (student system prompt,
user, bundled assistant tool-call+tool_response turns, final assistant JSON). The
tools are NOT stored per row -- we import the two tool callables here and pass them
as `tools=` to the chat template so the tool declarations render into the system turn
exactly as at inference.

Design decisions (see notes/runpod_sft.md and CLAUDE.md):
- LoRA (rank ~16-32) on a **bf16** base -- not full-FT, not 4-bit. Target: 2x H200.
- **Action-only** training data (no reasoning) -- handled upstream by build_sft.py.
- **assistant_only_loss fallback.** Gemma 4's chat template has NO `{% generation %}`
  markers, so TRL's `assistant_only_loss` is a silent no-op here (verified: the
  assistant mask comes back all-zero). We instead compute the assistant-token mask
  OURSELVES from the template's prefix-preservation property (see build_labels) and
  feed TRL a **pre-tokenized** dataset (input_ids/attention_mask/labels). TRL skips
  its own tokenization when a dataset already has `input_ids`, so our labels (with
  non-assistant tokens set to -100) are what the loss uses. `assistant_only_loss`
  is therefore left False in the SFTConfig on purpose.
- **Long sequences.** Episodes carry several capped scraped pages. Examples longer
  than --max-length are DROPPED (never right-truncated -- that would cut the final
  JSON target). gradient_checkpointing on; packing off (varlen packing needs
  FlashAttention, which cannot serve this model's head_dim=512 layers).
- **DDP-safe model load.** No `device_map` (breaks accelerate DDP); we reuse
  model.py's GQA/SDPA patch but omit its device_map. Launch under
  `accelerate launch`/`torchrun` (plain python = single process, GPU 2 idle).

On a successful run a `meta.json` lineage record (plan §6) is written next to the
adapter: base + dataset (by md5), the quant recipe, hyperparams, git sha.

Run (2x H200, from repo root, under tmux):
  accelerate launch --config_file configs/accelerate_ddp.yaml \
      scripts/train/train_sft.py --family gemma-4-e4b-it \
      --output-dir /workspace/gemma-menu-sft
  # torchrun equivalent:
  torchrun --nproc_per_node=2 scripts/train/train_sft.py --family gemma-4-e4b-it \
      --output-dir /workspace/gemma-menu-sft

Dev box (1x 24GB, no real training): --dry-run builds the dataset + resolved
config on CPU/tokenizer-only and prints one rendered+masked example, WITHOUT
loading the model or calling .train().
"""

