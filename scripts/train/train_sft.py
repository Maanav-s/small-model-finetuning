def _print_masked_example(tokenizer, ds) -> None:
    if len(ds) == 0:
        print("\n[dry-run] no examples survived filtering -- nothing to show.")
        return
    ex = ds[0]
    ids, labels = ex["input_ids"], ex["labels"]
    trained = [ids[t] for t in range(len(ids)) if labels[t] != -100]
    masked = [ids[t] for t in range(len(ids)) if labels[t] == -100]
    n_tr = len(trained)
    print("\n=== one rendered+masked example (row 0) ===")
    print(f"  total tokens: {len(ids)}   trained(loss): {n_tr} ({100*n_tr/len(ids):.1f}%)   "
          f"masked: {len(masked)}")
    print("  --- TRAINED (loss) tokens, decoded ---")
    print("   ", repr(tokenizer.decode(trained, skip_special_tokens=False)[:600]))
    print("  --- MASKED (-100) prefix, decoded ---")
    print("   ", repr(tokenizer.decode(masked, skip_special_tokens=False)[:300]), "...")


def _save_outputs(trainer, tokenizer, output_dir: str, attn: str) -> None:
    """Save the LoRA adapter AND a merged bf16 full checkpoint (+ tokenizer).

    The merged dir is a plain HF model so eval (scripts/eval_split.py --model gemma
    --model-path <dir>/merged) loads it with no peft dependency.
    """
    adapter_dir = os.path.join(output_dir, "adapter")
    merged_dir = os.path.join(output_dir, "merged")

    # Adapter: Trainer handles main-process-only saving under DDP.
    trainer.save_model(adapter_dir)
    if trainer.accelerator.is_main_process:
        tokenizer.save_pretrained(adapter_dir)

    trainer.accelerator.wait_for_everyone()
    if trainer.accelerator.is_main_process:
        import torch
        from peft import PeftModel
        from transformers import AutoModelForCausalLM
        from model import MODEL_ID, _force_repeat_kv_for_efficient_sdpa
        if attn == "sdpa":
            _force_repeat_kv_for_efficient_sdpa()
        print(f"Merging adapter -> bf16 full checkpoint at {merged_dir} ...", flush=True)
        base = AutoModelForCausalLM.from_pretrained(
            MODEL_ID, dtype=torch.bfloat16, attn_implementation=attn)
        merged = PeftModel.from_pretrained(base, adapter_dir).merge_and_unload()
        merged.save_pretrained(merged_dir, safe_serialization=True)
        tokenizer.save_pretrained(merged_dir)
        print(f"Saved adapter -> {adapter_dir}\nSaved merged model -> {merged_dir}")


