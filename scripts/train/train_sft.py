# ID of the single token the template emits to OPEN a tool_response block
# (`<|tool_response>`). It trails an assistant tool-call render but is produced by
# the environment, not the model (which stops at `<tool_call|>`), so build_labels
# trims it off the trained span. Resolved from the live tokenizer at runtime;
# this constant is only the fallback / documentation.
TOOL_RESPONSE_OPEN = "<|tool_response>"


# ---------------------------------------------------------------------------
# Pure helpers (unit-tested in tests/test_train_sft.py -- no GPU/model needed)
# ---------------------------------------------------------------------------
def effective_batch_size(per_device: int, grad_accum: int, num_processes: int) -> int:
    """Effective (global) batch = per_device x grad_accum x num_processes(GPUs)."""
    return per_device * grad_accum * num_processes


def trim_open_call_end(input_ids: list[int], end: int, tool_response_open_id: int) -> int:
    """Drop a trailing `<|tool_response>` opener from a tool-call span.

    An assistant message with tool_calls but no tool_responses renders as
    `...<tool_call|><|tool_response>` -- the template opens the response block for
    the (still absent) tool result. That opener token is emitted by the
    environment, not generated by the model (which stops at `<tool_call|>`), so it
    must not carry loss. `end` is the exclusive end index into `input_ids`; if the
    last token in the span is the opener, back it up by one.
    """
    if end > 0 and input_ids[end - 1] == tool_response_open_id:
        return end - 1
    return end


def partition_by_length(lengths: list[int], max_length: int) -> tuple[list[int], list[int]]:
    """Split example indices into (kept, dropped) by token length.

    Examples with length > max_length are DROPPED (not truncated) so the final
    JSON target is never clipped. length == 0 (a render failure sentinel) is also
    dropped. Returns (kept_indices, dropped_indices).
    """
    kept, dropped = [], []
    for i, n in enumerate(lengths):
        if 0 < n <= max_length:
            kept.append(i)
        else:
            dropped.append(i)
    return kept, dropped


def percentiles(values: list[int], ps=(50, 90, 95, 99, 100)) -> dict[int, int]:
    """Nearest-rank percentiles of a list of ints (empty -> zeros)."""
    if not values:
        return {p: 0 for p in ps}
    s = sorted(values)
    out = {}
    for p in ps:
        k = max(0, min(len(s) - 1, round(p / 100 * (len(s) - 1))))
        out[p] = s[k]
    return out


# ---------------------------------------------------------------------------
# Tokenization + assistant-only masking (needs the tokenizer + tool callables)
# ---------------------------------------------------------------------------
def _render_ids(tokenizer, tools, msgs: list[dict], add_gen: bool) -> list[int]:
    enc = tokenizer.apply_chat_template(
        msgs, tools=tools, add_generation_prompt=add_gen, tokenize=True, return_dict=True
    )
    return list(enc["input_ids"])


def build_labels(tokenizer, tools, messages: list[dict], tool_response_open_id: int,
                 assistant_only: bool = True) -> tuple[list[int], list[int]] | None:
    """Render `messages` and build the label mask.

    Returns (input_ids, labels). With assistant_only=True, only the tokens the
    MODEL generates -- each assistant tool-call emission and the final JSON answer
    -- carry loss; everything else (system, user, tool declarations, and the
    scraped tool_response bodies) is set to -100.

    How the mask is derived, given Gemma 4's template has no `{% generation %}`
    markers: the template is prefix-preserving for these single-task trajectories
    (CLAUDE.md), so for the assistant turn at index i the model's generated span is
    exactly [ len(render(messages[:i], add_gen=True)),  <end> ), where <end> is
      - for a tool-call turn: len(render(messages[:i] + [open tool_call], add_gen=False)),
        minus the trailing `<|tool_response>` opener the environment adds; or
      - for the final content turn: len(render(messages[:i+1], add_gen=False)),
        which includes the closing `<turn|>` so the model learns to stop.
    Each sub-render is asserted to be a genuine token-prefix of the full render; if
    that ever fails (a template change / an unexpected message shape) we return
    None so the caller DROPS the example rather than train on a wrong mask.
    """
    full_ids = _render_ids(tokenizer, tools, messages, add_gen=False)
    if assistant_only:
        labels = [-100] * len(full_ids)
    else:
        labels = list(full_ids)

    for i, msg in enumerate(messages):
        if msg.get("role") != "assistant":
            continue
        pre = _render_ids(tokenizer, tools, messages[:i], add_gen=True)
        if pre != full_ids[: len(pre)]:
            return None  # prefix broke -> unsafe to mask; drop
        start = len(pre)

        if msg.get("tool_calls"):
            open_msg = {"role": "assistant", "tool_calls": msg["tool_calls"]}
            end_ids = _render_ids(tokenizer, tools, messages[:i] + [open_msg], add_gen=False)
            if end_ids != full_ids[: len(end_ids)]:
                return None
            end = trim_open_call_end(full_ids, len(end_ids), tool_response_open_id)
        else:
            end_ids = _render_ids(tokenizer, tools, messages[: i + 1], add_gen=False)
            if end_ids != full_ids[: len(end_ids)]:
                return None
            end = len(end_ids)

        if assistant_only:
            for t in range(start, min(end, len(full_ids))):
                labels[t] = full_ids[t]

    return full_ids, labels


# ---------------------------------------------------------------------------
# Dataset construction
# ---------------------------------------------------------------------------
def load_rows(path: str) -> list[dict]:
    rows = []
    # build_sft.py writes UTF-8; read it as UTF-8 explicitly so a non-UTF-8
    # platform locale (e.g. Windows cp1252) can't mis-decode accented names.
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def build_dataset(rows, tokenizer, tools, max_length: int, assistant_only: bool):
    """Tokenize + mask every row, drop over-length/failed ones, return a HF Dataset.

    Returns (dataset, stats) where stats has example/drop counts and the length
    distribution. The dataset has exactly input_ids / attention_mask / labels.
    """
    from datasets import Dataset

    tr_open = tokenizer.convert_tokens_to_ids(TOOL_RESPONSE_OPEN)

    input_ids_all, labels_all, lengths_all = [], [], []
    render_errors = 0
    n = len(rows)
    for idx, row in enumerate(rows):
        if (idx + 1) % 100 == 0:
            print(f"  tokenizing {idx + 1}/{n} ...", flush=True)
        built = build_labels(tokenizer, tools, row["messages"], tr_open, assistant_only)
        if built is None:
            render_errors += 1
            input_ids_all.append([])
            labels_all.append([])
            lengths_all.append(0)
            continue
        ids, labels = built
        input_ids_all.append(ids)
        labels_all.append(labels)
        lengths_all.append(len(ids))

    kept, dropped = partition_by_length(lengths_all, max_length)
    dropped_len = sum(1 for i in dropped if lengths_all[i] > 0)

    ds = Dataset.from_dict({
        "input_ids": [input_ids_all[i] for i in kept],
        "attention_mask": [[1] * lengths_all[i] for i in kept],
        "labels": [labels_all[i] for i in kept],
    })

    kept_lengths = [lengths_all[i] for i in kept]
    stats = {
        "total": n,
        "render_errors": render_errors,
        "dropped_len": dropped_len,
        "kept": len(kept),
        "pct": percentiles([n for n in lengths_all if n > 0]),
        "pct_kept": percentiles(kept_lengths),
        "max_length": max_length,
    }
    return ds, stats


def print_dataset_stats(stats: dict) -> None:
    p = stats["pct"]
    print("\n=== dataset / token-length distribution (build_sft.py output) ===")
    print(f"  rows read:        {stats['total']}")
    print(f"  render errors:    {stats['render_errors']} (dropped -- prefix/mask unsafe)")
    print(f"  dropped >max_len: {stats['dropped_len']} (max_length={stats['max_length']})")
    print(f"  KEPT:             {stats['kept']}")
    print(f"  length p50/p90/p95/p99/max (all rows): "
          f"{p[50]}/{p[90]}/{p[95]}/{p[99]}/{p[100]}")
    frac_dropped = (stats["dropped_len"] / stats["total"]) if stats["total"] else 0.0
    if frac_dropped > 0.10:
        print(f"  [WARN] {frac_dropped:.0%} of examples dropped for length. Consider a "
              f"lower MAX_TOOL_CHARS in build_sft.py, or raise --max-length "
              f"(p95 is {p[95]}).")


# ---------------------------------------------------------------------------
# Model loading (DDP-safe -- NO device_map; reuse model.py's GQA/SDPA patch)
# ---------------------------------------------------------------------------
def load_base_model(attn: str = "sdpa"):
    """Load the bf16 base for training. No device_map (accelerate places it)."""
    import torch
    from transformers import AutoModelForCausalLM
    # model.py owns the SDPA GQA fix (forces repeat_kv so the mem-efficient kernel
    # serves Gemma 4's head_dim=512 layers instead of OOMing on MATH). Reuse it;
    # do NOT reuse its load_model (that pins device_map={"":0}, which breaks DDP).
    from model import MODEL_ID, _force_repeat_kv_for_efficient_sdpa

    if attn == "sdpa":
        _force_repeat_kv_for_efficient_sdpa()

    print(f"Loading {MODEL_ID} (bf16, attn={attn}, no device_map) ...", flush=True)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_ID, dtype=torch.bfloat16, attn_implementation=attn
    )
    model.config.use_cache = False  # required with gradient_checkpointing
    return model


# ---------------------------------------------------------------------------
# Collator: pad a pre-tokenized batch (input_ids/attention_mask/labels)
# ---------------------------------------------------------------------------
class PadCollator:
    """Right-pad pre-tokenized examples; pad labels with -100 so they carry no loss."""

    def __init__(self, pad_token_id: int):
        self.pad_token_id = pad_token_id

    def __call__(self, features):
        import torch
        maxlen = max(len(f["input_ids"]) for f in features)
        batch = {"input_ids": [], "attention_mask": [], "labels": []}
        for f in features:
            ids, am, lab = f["input_ids"], f["attention_mask"], f["labels"]
            pad = maxlen - len(ids)
            batch["input_ids"].append(ids + [self.pad_token_id] * pad)
            batch["attention_mask"].append(am + [0] * pad)
            batch["labels"].append(lab + [-100] * pad)
        return {k: torch.tensor(v, dtype=torch.long) for k, v in batch.items()}


